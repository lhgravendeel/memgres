-- ============================================================================
-- Feature Comparison: the CONTENT of information_schema
-- Target: PostgreSQL 18 vs Memgres
--
-- The shape of these views — which columns they have — is covered elsewhere.
-- What is checked here is whether the rows are there, because a standard view
-- that lists its columns and returns nothing is read by a tool as a definite
-- "no such thing" rather than as "I do not know":
--   * element_types is the only place a client can learn what an array column
--     holds, so an empty answer builds the wrong array decoder;
--   * constraint_table_usage answers "which foreign keys point at this table"
--     before a DROP, and it has to name the referenced table, not the
--     referencing one;
--   * the privilege views answer "may I write here", and PostgreSQL fills them
--     in from ownership without anyone having run a GRANT;
--   * views.check_option says whether a write through a view is checked at all.
--
-- Every case names a specific row with a WHERE that pins it and reads specific
-- columns. Nothing counts rows in a catalog: the two servers legitimately
-- contain different numbers of things.
-- ============================================================================

-- ============================================================================
-- Setup
-- ============================================================================

DROP SCHEMA IF EXISTS isv_s CASCADE;
DROP TYPE IF EXISTS isv_ct CASCADE;

CREATE SCHEMA isv_s;
CREATE DOMAIN isv_s.isv_dom AS varchar(10) CHECK (VALUE <> '');
CREATE DOMAIN isv_s.isv_dnum AS numeric(8,2);
CREATE TYPE isv_ct AS (x integer, y varchar(3), z timestamp(2));
CREATE TABLE isv_s.isv_parent (id int PRIMARY KEY, code varchar(20) UNIQUE);
CREATE TABLE isv_s.isv_child (
    cid int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid int REFERENCES isv_s.isv_parent(id) ON DELETE CASCADE ON UPDATE SET NULL,
    amt numeric(10,2) CONSTRAINT isv_amt_chk CHECK (amt > 0),
    note isv_s.isv_dom,
    tags text[],
    ts timestamp(3),
    created timestamptz,
    flag boolean NOT NULL);
CREATE TABLE isv_s.isv_types (
    c_bit8 bit(8), c_vbit bit varying(9), c_arr int[],
    c_dom isv_s.isv_dom, c_dnum isv_s.isv_dnum,
    c_ts0 timestamp(0), c_ts3 timestamp(3), c_time4 time(4),
    c_iv interval day to second(3));
CREATE VIEW isv_s.isv_v AS SELECT id, code FROM isv_s.isv_parent;
CREATE VIEW isv_s.isv_v2 AS SELECT id FROM isv_s.isv_parent WITH CHECK OPTION;
CREATE FUNCTION isv_s.isv_fn(a int, b text DEFAULT 'x') RETURNS int
    LANGUAGE sql AS $$ SELECT a $$;
CREATE FUNCTION isv_s.isv_trgfn() RETURNS trigger
    LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
CREATE TRIGGER isv_trg BEFORE INSERT OR UPDATE OF code ON isv_s.isv_parent
    FOR EACH ROW EXECUTE FUNCTION isv_s.isv_trgfn();

-- ============================================================================
-- Privilege views: what an owner holds without anyone having run a GRANT
-- ============================================================================

-- begin-expected
-- columns: privilege_type,is_grantable,with_hierarchy
-- row: DELETE | YES | NO
-- row: INSERT | YES | NO
-- row: REFERENCES | YES | NO
-- row: SELECT | YES | YES
-- row: TRIGGER | YES | NO
-- row: TRUNCATE | YES | NO
-- row: UPDATE | YES | NO
-- end-expected
SELECT privilege_type, is_grantable, with_hierarchy
  FROM information_schema.table_privileges
 WHERE table_schema = 'isv_s' AND table_name = 'isv_child' AND grantee = current_user
 ORDER BY privilege_type;

-- A view is a relation here too.
-- begin-expected
-- columns: privilege_type,is_grantable
-- row: SELECT | YES
-- end-expected
SELECT privilege_type, is_grantable
  FROM information_schema.table_privileges
 WHERE table_schema = 'isv_s' AND table_name = 'isv_v'
   AND grantee = current_user AND privilege_type = 'SELECT';

-- role_table_grants answers for the same named row. The role's own name differs
-- between the two servers, so it is compared to current_user rather than printed.
-- begin-expected
-- columns: grantor_is_owner,is_grantable,with_hierarchy
-- row: OWNER | YES | YES
-- end-expected
SELECT CASE WHEN grantor = current_user THEN 'OWNER' ELSE grantor END AS grantor_is_owner,
       is_grantable, with_hierarchy
  FROM information_schema.role_table_grants
 WHERE table_schema = 'isv_s' AND table_name = 'isv_child'
   AND privilege_type = 'SELECT' AND grantee = current_user;

-- Only four privileges exist at column granularity.
-- begin-expected
-- columns: column_name,privilege_type,is_grantable
-- row: code | INSERT | YES
-- row: code | REFERENCES | YES
-- row: code | SELECT | YES
-- row: code | UPDATE | YES
-- row: id | INSERT | YES
-- row: id | REFERENCES | YES
-- row: id | SELECT | YES
-- row: id | UPDATE | YES
-- end-expected
SELECT column_name, privilege_type, is_grantable
  FROM information_schema.column_privileges
 WHERE table_schema = 'isv_s' AND table_name = 'isv_parent' AND grantee = current_user
 ORDER BY column_name, privilege_type;

-- begin-expected
-- columns: grantor_is_owner,is_grantable
-- row: OWNER | YES
-- end-expected
SELECT CASE WHEN grantor = current_user THEN 'OWNER' ELSE grantor END AS grantor_is_owner,
       is_grantable
  FROM information_schema.role_column_grants
 WHERE table_schema = 'isv_s' AND table_name = 'isv_parent'
   AND column_name = 'code' AND privilege_type = 'UPDATE' AND grantee = current_user;

-- EXECUTE goes to the owner and to PUBLIC, which is why anyone else may call it.
-- begin-expected
-- columns: grantee,privilege_type,is_grantable
-- row: PUBLIC | EXECUTE | NO
-- row: OWNER | EXECUTE | YES
-- end-expected
SELECT CASE WHEN grantee = current_user THEN 'OWNER' ELSE grantee END AS grantee,
       privilege_type, is_grantable
  FROM information_schema.routine_privileges
 WHERE routine_schema = 'isv_s' AND routine_name = 'isv_fn'
 ORDER BY is_grantable;

-- routine_privileges joins to routines on the specific name, or nothing can get
-- from a privilege to the routine it is about.
-- begin-expected
-- columns: routine_name,privilege_type
-- row: isv_fn | EXECUTE
-- end-expected
SELECT p.routine_name, p.privilege_type
  FROM information_schema.routine_privileges p
  JOIN information_schema.routines r
    ON r.specific_schema = p.specific_schema AND r.specific_name = p.specific_name
 WHERE p.routine_schema = 'isv_s' AND p.routine_name = 'isv_fn' AND p.grantee = current_user;

-- role_routine_grants keeps the grant to PUBLIC: PG's role_* views filter on the
-- grantor and grantee being roles the session may act as, and PUBLIC always is.
-- begin-expected
-- columns: grantee,privilege_type,is_grantable
-- row: PUBLIC | EXECUTE | NO
-- row: OWNER | EXECUTE | YES
-- end-expected
SELECT CASE WHEN grantee = current_user THEN 'OWNER' ELSE grantee END AS grantee,
       privilege_type, is_grantable
  FROM information_schema.role_routine_grants
 WHERE routine_schema = 'isv_s' AND routine_name = 'isv_trgfn'
 ORDER BY is_grantable;

-- A relation has a composite type of its own, and USAGE on it is reported here.
-- begin-expected
-- columns: grantee,privilege_type,is_grantable
-- row: PUBLIC | TYPE USAGE | NO
-- row: OWNER | TYPE USAGE | YES
-- end-expected
SELECT CASE WHEN grantee = current_user THEN 'OWNER' ELSE grantee END AS grantee,
       privilege_type, is_grantable
  FROM information_schema.udt_privileges
 WHERE udt_schema = 'isv_s' AND udt_name = 'isv_parent'
 ORDER BY is_grantable;

-- begin-expected
-- columns: privilege_type,is_grantable
-- row: TYPE USAGE | YES
-- end-expected
SELECT privilege_type, is_grantable
  FROM information_schema.udt_privileges
 WHERE udt_name = 'isv_ct' AND grantee = current_user;

-- begin-expected
-- columns: grantee,object_type,privilege_type,is_grantable
-- row: PUBLIC | DOMAIN | USAGE | NO
-- row: OWNER | DOMAIN | USAGE | YES
-- end-expected
SELECT CASE WHEN grantee = current_user THEN 'OWNER' ELSE grantee END AS grantee,
       object_type, privilege_type, is_grantable
  FROM information_schema.usage_privileges
 WHERE object_schema = 'isv_s' AND object_name = 'isv_dom'
 ORDER BY is_grantable;

-- One type descriptor per column of a table.
-- begin-expected
-- columns: object_type,dtd_identifier
-- row: TABLE | 1
-- row: TABLE | 2
-- row: TABLE | 3
-- row: TABLE | 4
-- row: TABLE | 5
-- row: TABLE | 6
-- row: TABLE | 7
-- row: TABLE | 8
-- end-expected
SELECT object_type, dtd_identifier
  FROM information_schema.data_type_privileges
 WHERE object_schema = 'isv_s' AND object_name = 'isv_child'
 ORDER BY dtd_identifier;

-- A domain has exactly one, and a routine has one per parameter plus 0 for its result.
-- begin-expected
-- columns: object_type,dtd_identifier
-- row: DOMAIN | 1
-- end-expected
SELECT object_type, dtd_identifier
  FROM information_schema.data_type_privileges
 WHERE object_schema = 'isv_s' AND object_name = 'isv_dnum';

-- begin-expected
-- columns: dtd_identifier
-- row: 0
-- row: 1
-- row: 2
-- end-expected
SELECT p.dtd_identifier
  FROM information_schema.data_type_privileges p
  JOIN information_schema.routines r
    ON r.specific_schema = p.object_schema AND r.specific_name = p.object_name
 WHERE p.object_type = 'ROUTINE' AND r.routine_name = 'isv_fn'
 ORDER BY p.dtd_identifier;

-- ============================================================================
-- element_types: what an array column holds
-- ============================================================================

-- tags is the fifth column of isv_child, so the element descriptor is a5.
-- begin-expected
-- columns: object_type,collection_type_identifier,data_type,udt_schema,udt_name,dtd_identifier
-- row: TABLE | 5 | text | pg_catalog | text | a5
-- end-expected
SELECT object_type, collection_type_identifier, data_type, udt_schema, udt_name, dtd_identifier
  FROM information_schema.element_types
 WHERE object_schema = 'isv_s' AND object_name = 'isv_child';

-- begin-expected
-- columns: collection_type_identifier,data_type,udt_name,dtd_identifier
-- row: 3 | integer | int4 | a3
-- end-expected
SELECT collection_type_identifier, data_type, udt_name, dtd_identifier
  FROM information_schema.element_types
 WHERE object_schema = 'isv_s' AND object_name = 'isv_types';

-- The join a driver makes to build an array decoder: from the ARRAY column in
-- columns to its element type, on the dtd_identifier.
-- begin-expected
-- columns: column_name,data_type,udt_name
-- row: tags | ARRAY | text
-- end-expected
SELECT c.column_name, c.data_type, e.udt_name
  FROM information_schema.columns c
  JOIN information_schema.element_types e
    ON e.object_catalog = c.table_catalog
   AND e.object_schema = c.table_schema
   AND e.object_name = c.table_name
   AND e.object_type = 'TABLE'
   AND e.collection_type_identifier = c.dtd_identifier
 WHERE c.table_schema = 'isv_s' AND c.table_name = 'isv_child';

