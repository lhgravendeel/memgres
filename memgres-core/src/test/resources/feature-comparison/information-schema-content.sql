-- A text default carries the cast that gives it its type.
-- begin-expected
-- columns: parameter_name,ordinal_position,parameter_mode,data_type,udt_schema,udt_name,parameter_default
-- row: a | 1 | IN | integer | pg_catalog | int4 | NULL
-- row: b | 2 | IN | text | pg_catalog | text | 'x'::text
-- end-expected
SELECT p.parameter_name, p.ordinal_position, p.parameter_mode, p.data_type,
       p.udt_schema, p.udt_name, p.parameter_default
  FROM information_schema.parameters p
  JOIN information_schema.routines r
    ON r.specific_schema = p.specific_schema AND r.specific_name = p.specific_name
 WHERE r.routine_name = 'isv_fn'
 ORDER BY p.ordinal_position;

