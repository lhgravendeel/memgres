-- A bit string declares its width in bits, so it has a maximum length and no
-- octet length.
-- begin-expected
-- columns: column_name,data_type,udt_name,character_maximum_length,character_octet_length
-- row: c_bit8 | bit | bit | 8 | NULL
-- row: c_vbit | bit varying | varbit | 9 | NULL
-- end-expected
SELECT column_name, data_type, udt_name, character_maximum_length, character_octet_length
  FROM information_schema.columns
 WHERE table_schema = 'isv_s' AND table_name = 'isv_types'
   AND column_name IN ('c_bit8', 'c_vbit')
 ORDER BY column_name;

-- The typmod of a temporal column is its datetime_precision.
-- begin-expected
-- columns: column_name,data_type,datetime_precision,interval_type
-- row: c_ts0 | timestamp without time zone | 0 | NULL
-- row: c_ts3 | timestamp without time zone | 3 | NULL
-- row: c_time4 | time without time zone | 4 | NULL
-- row: c_iv | interval | 3 | DAY TO SECOND(3)
-- end-expected
SELECT column_name, data_type, datetime_precision, interval_type
  FROM information_schema.columns
 WHERE table_schema = 'isv_s' AND table_name = 'isv_types'
   AND column_name IN ('c_ts0', 'c_ts3', 'c_time4', 'c_iv')
 ORDER BY ordinal_position;

-- WITH CHECK OPTION is what stops a write through the view from disappearing.
-- begin-expected
-- columns: table_name,check_option,is_updatable,is_insertable_into
