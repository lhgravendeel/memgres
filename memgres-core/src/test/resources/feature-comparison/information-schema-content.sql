-- begin-expected
-- columns: attribute_name,ordinal_position,data_type,character_maximum_length,character_octet_length,numeric_precision,numeric_precision_radix,numeric_scale,datetime_precision,attribute_udt_schema,attribute_udt_name,dtd_identifier,is_derived_reference_attribute
-- row: x | 1 | integer | NULL | NULL | 32 | 2 | 0 | NULL | pg_catalog | int4 | 1 | NO
