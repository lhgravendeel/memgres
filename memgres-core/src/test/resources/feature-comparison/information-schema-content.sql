SELECT attribute_name, ordinal_position, data_type,
       character_maximum_length, character_octet_length,
       numeric_precision, numeric_precision_radix, numeric_scale,
       datetime_precision, attribute_udt_schema, attribute_udt_name,
       dtd_identifier, is_derived_reference_attribute
  FROM information_schema.attributes
 WHERE udt_name = 'isv_ct'
 ORDER BY ordinal_position;

-- PG answers the first columns for a composite type and leaves the rest null:
-- is_final and the ordering columns describe a DISTINCT type, which PG has none of.
-- begin-expected
-- columns: user_defined_type_schema,user_defined_type_category,is_instantiable,is_final,ordering_form,reference_type,data_type
-- row: public | STRUCTURED | YES | NULL | NULL | NULL | NULL
-- end-expected
SELECT user_defined_type_schema, user_defined_type_category, is_instantiable,
       is_final, ordering_form, reference_type, data_type
  FROM information_schema.user_defined_types
 WHERE user_defined_type_name = 'isv_ct';

