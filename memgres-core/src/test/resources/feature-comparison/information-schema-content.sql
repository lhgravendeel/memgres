-- The FK lives on isv_child; the view names the table it points AT. This is the
-- query that answers "which constraints depend on this table" before a DROP.
-- begin-expected
-- columns: table_schema,table_name
-- row: isv_s | isv_parent
-- end-expected
SELECT table_schema, table_name
  FROM information_schema.constraint_table_usage
 WHERE constraint_name = 'isv_child_pid_fkey';

-- PG lists PRIMARY KEY, UNIQUE and FOREIGN KEY here and nothing else — no CHECK,
-- and none of the NOT NULL constraints PG 18 synthesizes.
-- begin-expected
-- columns: constraint_name,table_name
-- row: isv_child_pid_fkey | isv_parent
-- row: isv_child_pkey | isv_child
-- row: isv_parent_code_key | isv_parent
-- row: isv_parent_pkey | isv_parent
-- end-expected
SELECT constraint_name, table_name
  FROM information_schema.constraint_table_usage
 WHERE table_schema = 'isv_s'
 ORDER BY constraint_name;

-- begin-expected
-- columns: constraint_schema,constraint_name,domain_schema,domain_name,is_deferrable,initially_deferred
-- row: isv_s | isv_dom_check | isv_s | isv_dom | NO | NO
-- end-expected
SELECT constraint_schema, constraint_name, domain_schema, domain_name,
       is_deferrable, initially_deferred
  FROM information_schema.domain_constraints
 WHERE domain_schema = 'isv_s';

-- A domain's CHECK is filed under the domain's own schema, not under public.
-- begin-expected
-- columns: check_clause
-- row: ((VALUE)::text <> ''::text)
-- end-expected
SELECT check_clause
  FROM information_schema.check_constraints
 WHERE constraint_schema = 'isv_s' AND constraint_name = 'isv_dom_check';

-- begin-expected
