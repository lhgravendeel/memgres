-- begin-expected
-- columns: table_type,data_type,privilege_type
-- row: BASE TABLE | character varying | SELECT
-- end-expected
SELECT t.table_type, c.data_type, cp.privilege_type
  FROM information_schema.tables t
  JOIN information_schema.columns c
    ON c.table_schema = t.table_schema AND c.table_name = t.table_name
  JOIN information_schema.column_privileges cp
    ON cp.table_schema = c.table_schema AND cp.table_name = c.table_name
   AND cp.column_name = c.column_name
 WHERE t.table_schema = 'isv_s' AND t.table_name = 'isv_parent'
   AND c.column_name = 'code' AND cp.privilege_type = 'SELECT'
   AND cp.grantee = current_user;

-- begin-expected
-- columns: check_option,data_type
-- row: CASCADED | integer
-- end-expected
SELECT v.check_option, c.data_type
  FROM information_schema.views v
  JOIN information_schema.view_column_usage u
    ON u.view_schema = v.table_schema AND u.view_name = v.table_name
  JOIN information_schema.columns c
    ON c.table_schema = u.table_schema AND c.table_name = u.table_name
   AND c.column_name = u.column_name
 WHERE v.table_schema = 'isv_s' AND v.table_name = 'isv_v2';

