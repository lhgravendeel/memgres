-- ============================================================================
-- Feature Comparison: smallint/real overflow must raise 22003
-- Target: PostgreSQL 18 vs Memgres
-- ============================================================================
-- PG: 40000::smallint → ERROR 22003 (not silent wraparound to -25536).
-- PG: 1e40::real → ERROR 22003 (not Infinity).
-- ============================================================================

-- ============================================================================
-- 1. Valid smallint max boundary
-- ============================================================================

-- begin-expected
-- columns: result
-- row: 32767
-- end-expected
SELECT 32767::smallint AS result;

-- ============================================================================
-- 2. smallint overflow (positive) → error
-- ============================================================================

-- begin-expected-error
-- error: 22003
-- end-expected
SELECT 40000::smallint;

-- ============================================================================
-- 3. smallint overflow (negative) → error
-- ============================================================================

-- begin-expected-error
-- error: 22003
-- end-expected
SELECT (-40000)::smallint;

-- ============================================================================
-- 4. real overflow → error
-- ============================================================================

-- begin-expected-error
-- error: 22003
-- end-expected
SELECT 1e40::real;
