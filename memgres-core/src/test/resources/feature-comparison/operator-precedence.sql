-- ============================================================================
-- Feature Comparison: Bitwise/shift operators below +/- in precedence
-- Target: PostgreSQL 18 vs Memgres
-- ============================================================================
-- PG precedence: + - bind tighter than & | # << >>.
-- So 2 & 3 + 1 = 2 & (3+1) = 2 & 4 = 0, not (2&3)+1 = 3.
-- ============================================================================

-- ============================================================================
-- 1. Bitwise AND below addition
-- ============================================================================

-- begin-expected
-- columns: result
-- row: 0
-- end-expected
SELECT 2 & 3 + 1 AS result;

-- ============================================================================
-- 2. Shift left below addition
-- ============================================================================

-- begin-expected
-- columns: result
-- row: 20
-- end-expected
SELECT 2 + 8 << 1 AS result;

-- ============================================================================
-- 3. Bitwise OR below subtraction
-- ============================================================================

-- begin-expected
-- columns: result
-- row: 7
-- end-expected
SELECT 7 | 8 - 1 AS result;

-- ============================================================================
-- 4. Bitwise XOR below addition
-- ============================================================================

-- begin-expected
-- columns: result
-- row: 1
-- end-expected
SELECT 5 # 3 + 1 AS result;
