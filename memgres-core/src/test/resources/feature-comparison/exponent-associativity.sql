-- ============================================================================
-- Feature Comparison: ^ exponentiation is left-associative
-- Target: PostgreSQL 18 vs Memgres
-- ============================================================================
-- PG: 2^3^2 = (2^3)^2 = 64. Right-associative would give 2^(3^2) = 512.
-- ============================================================================

-- ============================================================================
-- 1. Basic left-associativity
-- ============================================================================

-- begin-expected
-- columns: result
-- row: 64
-- end-expected
SELECT 2^3^2 AS result;

-- ============================================================================
-- 2. Triple chaining
-- ============================================================================

-- begin-expected
-- columns: result
-- row: 256
-- end-expected
SELECT 2^2^2^2 AS result;

-- ============================================================================
-- 3. Explicit right grouping differs
-- ============================================================================

-- begin-expected
-- columns: result
-- row: 512
-- end-expected
SELECT 2^(3^2) AS result;
