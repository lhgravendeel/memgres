/**
 * The operators PostgreSQL registers over the types memgres models.
 *
 * <p>An operator row without operand types identifies nothing: two different {@code +}
 * operators are indistinguishable, and anything that consults pg_operator to decide whether
 * an expression is legal, or to enumerate what a type supports, learns only a spelling. Each
 * row here therefore carries what PostgreSQL 18 carries -- left and right operand type, result
 * type, the function behind it, and its commutator and negator.
 *
 * <p>Columns: oprname, oprkind, oprleft, oprright, oprresult, oprcode (function name),
 * oprcanmerge, oprcanhash, commutator signature, negator signature, oid. A signature is
 * "name left right", or empty when there is none.
 *
 * <p>The last column is PostgreSQL's own OID for the operator. It is not decoration: every
 * built-in object in a PostgreSQL catalogue has a fixed OID below 16384, and that boundary is
 * how a client tells what the server ships from what somebody created — pg_dump, a migration
 * tool deciding what to emit, and any query filtering {@code oid < 16384} all read it. Minting
 * these from the user-object counter said all 799 shipped operators were user-defined, and left
 * {@code '=(int4,int4)'::regoperator} answering a number no PostgreSQL server would recognise.
 *
 * <p>oprcanmerge and oprcanhash carry PostgreSQL's own values as well. A planner reads them to
 * decide whether an equality operator admits a merge join or a hash join; reporting false for
 * {@code =(int4,int4)} says the commonest join in SQL can only be done by nested loop.
 */
