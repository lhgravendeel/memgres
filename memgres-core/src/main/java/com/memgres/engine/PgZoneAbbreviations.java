    private static final Map<String, String[]> BY_ZONE = byZone();

    private static Map<String, String[]> byZone() {
        Map<String, String[]> m = new HashMap<String, String[]>();
        for (String entry : MEASURED) {
            int first = entry.indexOf('|');
            int second = entry.indexOf('|', first + 1);
            m.put(entry.substring(0, first), new String[]{
                    entry.substring(first + 1, second), entry.substring(second + 1)});
        }
        return Collections.unmodifiableMap(m);
    }

    /**
     * The abbreviation a zone writes at an instant, or null for a zone PostgreSQL does not carry.
     *
     * <p>Which of the two recorded abbreviations applies is decided by the displacement in force,
     * so a zone south of the equator is read the right way round, and so is a zone that changes
     * its displacement without calling the change summer time — Casey station keeps no summer
     * time and still moves between two abbreviations.
     */
    static String at(ZoneId zone, Instant when) {
        String[] pair = BY_ZONE.get(zone.getId());
        if (pair == null) return null;
        if (pair[0].equals(pair[1])) return pair[0];
        ZoneRules rules = zone.getRules();
        ZoneOffset now = rules.getOffset(when);
        if (now.equals(rules.getOffset(IN_JANUARY))) return pair[0];
        if (now.equals(rules.getOffset(IN_JULY))) return pair[1];
        // A displacement neither sample saw: summer time says which half of the year it belongs to.
        return rules.isDaylightSavings(when) == rules.isDaylightSavings(IN_JANUARY)
                ? pair[0] : pair[1];
    }
